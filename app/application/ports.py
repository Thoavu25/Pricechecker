"""Interfaces required by application services; Infrastructure supplies adapters."""

from datetime import datetime
from decimal import Decimal
from typing import Protocol

from app.domain.entities import Account, Discount, Price, StoreQuote
from app.domain.pricing import PriceLabelStrategy


class UserRepository(Protocol):
    def get_by_username(self, username: str) -> Account | None: ...
    def get(self, user_id: int) -> Account | None: ...
    def add(self, user: Account) -> Account: ...
    def pending_stores(self) -> list[Account]: ...
    def stores(self) -> list[Account]: ...
    def save(self, user: Account) -> None: ...
    def delete(self, user: Account) -> None: ...
    def active_admin_count(self) -> int: ...


class PriceRepository(Protocol):
    def add_price(self, store_id: int, barcode_type: str, gtin: str,
                  amount: Decimal, recorded_at: datetime) -> None: ...
    def add_price_batch(self, store_id: int, prices: list[dict]) -> None: ...
    def add_discount(self, store_id: int, barcode_type: str, gtin: str,
                     percentage: Decimal, starts_at: datetime,
                     ends_at: datetime | None) -> Discount: ...
    def record_shopper_search(self, shopper_id: int, barcode_type: str, gtin: str,
                              amount: Decimal, latitude: float, longitude: float,
                              searched_at: datetime) -> None: ...
    def nearby_product_prices(self, barcode_type: str, gtin: str) -> list[StoreQuote]: ...


class AuditRepository(Protocol):
    def record(self, actor_id: int, action: str,
               target_user_id: int | None, details: str) -> None: ...
    def list_all(self): ...


class TokenService(Protocol):
    def create(self, user_id: int, role: str) -> str: ...
    def read_claims(self, token: str) -> dict: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...
